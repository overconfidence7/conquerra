import puppeteer from "puppeteer-core";
const [tag, out] = process.argv.slice(2);
const b = await puppeteer.launch({ executablePath: "C:/Program Files/Google/Chrome/Application/chrome.exe", headless: true, args: ["--enable-gpu", "--use-angle=d3d11"] });
const p = await b.newPage();
await p.setViewport({ width: 1440, height: 1700 });
await p.goto("http://localhost:5173/?lab=bench&part=redo", { waitUntil: "networkidle0" });
await new Promise((r) => setTimeout(r, 2500));
const el = await p.$("#redo");
const box = await el.boundingBox();
await p.screenshot({ path: `${out}/conifer-${tag}.png`, clip: { x: box.x, y: box.y + 750, width: Math.min(box.width, 1400), height: 450 } });
await p.setViewport({ width: 1440, height: 900 });
await p.goto("http://localhost:5173/?lab=bench&part=sprites", { waitUntil: "networkidle0" });
await new Promise((r) => setTimeout(r, 5000));
await p.screenshot({ path: `${out}/conifer-${tag}-map.png` });
await b.close();
